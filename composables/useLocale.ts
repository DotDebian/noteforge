const timeAgoMessages: Record<Locale, UseTimeAgoMessages> = {
  en: {
    justNow: 'just now',
    past: (n: string) => (/\d/.test(n) ? `${n} ago` : n),
    future: (n: string) => (/\d/.test(n) ? `in ${n}` : n),
    invalid: '',
    second: (n: number) => `${n} second${n === 1 ? '' : 's'}`,
    minute: (n: number) => `${n} minute${n === 1 ? '' : 's'}`,
    hour: (n: number) => `${n} hour${n === 1 ? '' : 's'}`,
    day: (n: number) => `${n} day${n === 1 ? '' : 's'}`,
    week: (n: number) => `${n} week${n === 1 ? '' : 's'}`,
    month: (n: number) => `${n} month${n === 1 ? '' : 's'}`,
    year: (n: number) => `${n} year${n === 1 ? '' : 's'}`,
  },
  fr: {
    justNow: 'à l’instant',
    past: (n: string) => (/\d/.test(n) ? `il y a ${n}` : n),
    future: (n: string) => (/\d/.test(n) ? `dans ${n}` : n),
    invalid: '',
    second: (n: number) => `${n} seconde${n === 1 ? '' : 's'}`,
    minute: (n: number) => `${n} minute${n === 1 ? '' : 's'}`,
    hour: (n: number) => `${n} heure${n === 1 ? '' : 's'}`,
    day: (n: number) => `${n} jour${n === 1 ? '' : 's'}`,
    week: (n: number) => `${n} semaine${n === 1 ? '' : 's'}`,
    // French: "mois" and "ans" — "mois" is invariable in plural.
    month: (n: number) => `${n} mois`,
    year: (n: number) => `${n} an${n === 1 ? '' : 's'}`,
  },
}

/**
 * Lightweight i18n. Locale is persisted in localStorage under
 * `noteforge-locale` and synced with `<html lang>`. `t(key)` falls back to
 * the English string, then the key itself.
 */
export function useLocale() {
  const locale = useStorage<Locale>('noteforge-locale', detectInitial())

  if (typeof document !== 'undefined') {
    document.documentElement.setAttribute('lang', locale.value)
  }

  function setLocale(next: Locale) {
    locale.value = next
    if (typeof document !== 'undefined') {
      document.documentElement.setAttribute('lang', next)
    }
  }

  function toggle() {
    setLocale(locale.value === 'fr' ? 'en' : 'fr')
  }

  function t(key: string, params?: Record<string, string | number>): string {
    const raw = dictionaries[locale.value]?.[key] ?? en[key] ?? key
    return format(raw, params)
  }

  const isFr = computed(() => locale.value === 'fr')

  return { locale, isFr, t, setLocale, toggle }
}

/**
 * Locale-reactive "X minutes ago" formatter, drop-in replacement for
 * `useTimeAgo` that re-renders instantly when the language toggles. Reads
 * `useNow()` so it updates every 30 s like the VueUse original.
 */
export function useLocalizedTimeAgo(
  time: MaybeRefOrGetter<Date | number | string | null | undefined>,
) {
  const { locale } = useLocale()
  const now = useNow({ interval: 30_000 })

  return computed(() => {
    const raw = toValue(time)
    if (raw == null) return ''
    const d = raw instanceof Date ? raw : new Date(raw)
    if (Number.isNaN(d.getTime())) return ''

    const msgs = timeAgoMessages[locale.value]
    const diffMs = now.value.getTime() - d.getTime()
    const isPast = diffMs >= 0
    const abs = Math.abs(diffMs)

    if (abs < 60_000) return msgs.justNow

    const units: { ms: number, fn: (n: number) => string }[] = [
      { ms: 60_000, fn: msgs.minute as (n: number) => string },
      { ms: 3_600_000, fn: msgs.hour as (n: number) => string },
      { ms: 86_400_000, fn: msgs.day as (n: number) => string },
      { ms: 604_800_000, fn: msgs.week as (n: number) => string },
      { ms: 2_592_000_000, fn: msgs.month as (n: number) => string },
      { ms: 31_536_000_000, fn: msgs.year as (n: number) => string },
    ]
    // Pick the largest unit that yields a value >= 1.
    let chosen = units[0]
    for (const u of units) {
      if (abs >= u.ms) chosen = u
      else break
    }
    if (!chosen) return msgs.justNow
    const n = Math.round(abs / chosen.ms)
    const body = chosen.fn(n)
    const wrap = isPast ? msgs.past : msgs.future
    return typeof wrap === 'function' ? wrap(body, isPast) : wrap
  })
}
